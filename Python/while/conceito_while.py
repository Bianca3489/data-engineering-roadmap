# Conceito While - estrutura de repetião com teste lógico

# conceito : while significa 'enquanto' em inglês. 'é uma estrutura de repetição com teste lógico'

# -----------------------------------------------------------

# A  estrutura de repetição while serve para repetir um bloco de código enquanto uma condição for verdadeira

#Exemplos:
# while condicao:
#    codigo

# -----------------------------------------------------------
# -----------------------------------------

i = 0
while i < 5:
    print("Contagem: ", i)
    i += 1